// In the PDF rubrics, Total Nilai is the direct sum of the scores of all aspects
// (e.g., 7 aspects x 80 = 560 max per judge, as explicitly shown in the PDF scoring tables).
export function calculateWeightedJuryScore(
  kriteriaList: CabangLomba['kriteria'],
  scores: Record<string, number>
): number {
  let total = 0;
  kriteriaList.forEach((k) => {
    const rawScore = scores[k.id] || 0;
    total += rawScore;
  });
  return Math.round(total * 100) / 100;
}

